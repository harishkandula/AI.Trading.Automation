_ALL: list[SymbolMeta] = []
_seen: set[str] = set()
for _entry in _LARGE_CAP + _MID_CAP + _SMALL_CAP:
    if _entry.symbol not in _seen:
        _seen.add(_entry.symbol)
        _ALL.append(_entry)

NIFTY500: list[SymbolMeta] = _ALL

# Convenience lookups
SYMBOL_TO_META: dict[str, SymbolMeta] = {m.symbol: m for m in NIFTY500}
SYMBOL_TO_SEGMENT: dict[str, str] = {m.symbol: m.segment for m in NIFTY500}
SYMBOL_TO_SECTOR: dict[str, str] = {m.symbol: m.sector for m in NIFTY500}


def all_symbols(segment: str | None = None) -> list[str]:
    """Return symbols, optionally filtered by segment (LARGE/MID/SMALL)."""
    if segment:
        seg = segment.upper()
        return [m.symbol for m in NIFTY500 if m.segment == seg]
    return [m.symbol for m in NIFTY500]


def symbols_by_sector(sector: str) -> list[str]:
    return [m.symbol for m in NIFTY500 if m.sector == sector]


def all_sectors() -> list[str]:
    return sorted({m.sector for m in NIFTY500})
