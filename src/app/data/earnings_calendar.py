# Parse dates once at import time
_PARSED: dict[str, list[date]] = {
    sym: [date.fromisoformat(d) for d in dates]
    for sym, dates in _EARNINGS_DATES.items()
}


def has_upcoming_earnings(symbol: str, as_of: date, window_days: int = 5) -> bool:
    """Return True if *symbol* has earnings within *window_days* of *as_of*.

    Symbols not in the calendar always return False (no blackout).
    """
    dates = _PARSED.get(symbol)
    if not dates:
        return False
    for d in dates:
        if 0 <= (d - as_of).days <= window_days:
            return True
    return False


def days_to_next_earnings(symbol: str, as_of: date) -> int | None:
    """Return calendar days until the next earnings date, or None if not in calendar."""
    dates = _PARSED.get(symbol)
    if not dates:
        return None
    future = [d for d in dates if d >= as_of]
    if not future:
        return None
    return (min(future) - as_of).days
